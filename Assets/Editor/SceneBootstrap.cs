        /// <summary>
        /// Fills the CardSpriteLibrary asset from Assets/Art/Cards. File names encode the
        /// suit and rank: card_&lt;Suit&gt;_&lt;01..13&gt;.png, Suit spelled as the C# enum.
        /// </summary>
        private static void PopulateCardLibrary()
        {
            CardSpriteLibrary library = RequireAsset<CardSpriteLibrary>(CardLibraryPath);
            var so = new SerializedObject(library);

            SerializedProperty faces = so.FindProperty("_faces");
            faces.arraySize = CardSpriteLibrary.FaceCount;

            var missing = new List<string>();
            foreach (Suit suit in (Suit[])Enum.GetValues(typeof(Suit)))
            {
                for (int rank = 1; rank <= 13; rank++)
                {
                    string path = $"{CardArtFolder}/card_{suit}_{rank:00}.png";
                    var sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path);
                    if (sprite == null) missing.Add(path);
                    int index = CardSpriteLibrary.IndexOf(new Card(suit, (Rank)rank));
                    faces.GetArrayElementAtIndex(index).objectReferenceValue = sprite;
                }
            }

            var back = AssetDatabase.LoadAssetAtPath<Sprite>($"{CardArtFolder}/card_Back.png");
            if (back == null) missing.Add($"{CardArtFolder}/card_Back.png");
            so.FindProperty("_back").objectReferenceValue = back;

            so.ApplyModifiedPropertiesWithoutUndo();
            EditorUtility.SetDirty(library);

            if (missing.Count > 0)
            {
                throw new InvalidOperationException(
                    $"{missing.Count} card sprite(s) missing, first: {missing[0]}. " +
                    "Run 'python3 art-source/generate_premium_art.py' from the project root. " +
                    "If the PNGs exist, they may have imported as Textures rather than Sprites — " +
                    "ArtImportSettings should prevent that.");
            }
            Debug.Log($"[SceneBootstrap] Card library populated ({CardSpriteLibrary.FaceCount} faces + back).");
        }

        /// <summary>Colourways whose value is printed in dark ink (the light chips).</summary>
        private static readonly HashSet<int> DarkLabelChips = new HashSet<int> { 1, 1000, 10000 };

        /// <summary>Fills the ChipSpriteLibrary from Assets/Art/Chips: chip_&lt;value&gt;.png + _side.png.</summary>
        private static void PopulateChipLibrary()
        {
            ChipSpriteLibrary library = RequireAsset<ChipSpriteLibrary>(ChipLibraryPath);
            var so = new SerializedObject(library);

            var values = new List<int>();
            foreach (string path in ArtFiles(ChipArtFolder, "chip_*.png"))
            {
                Match m = Regex.Match(Path.GetFileNameWithoutExtension(path), @"^chip_(\d+)$");
                if (m.Success) values.Add(int.Parse(m.Groups[1].Value));
            }
            values.Sort();
            if (values.Count == 0)
                throw new InvalidOperationException(
                    "No chip art (chip_<value>.png) in " + ChipArtFolder + ". Run art-source/generate_premium_art.py.");

            SerializedProperty entries = so.FindProperty("_entries");
            entries.arraySize = values.Count;
            for (int i = 0; i < values.Count; i++)
            {
                SerializedProperty e = entries.GetArrayElementAtIndex(i);
                e.FindPropertyRelative("Value").intValue = values[i];
                e.FindPropertyRelative("Face").objectReferenceValue = ChipArt($"chip_{values[i]}");
                e.FindPropertyRelative("Side").objectReferenceValue = ChipArt($"chip_{values[i]}_side");
                e.FindPropertyRelative("DarkLabel").boolValue = DarkLabelChips.Contains(values[i]);
            }
            so.FindProperty("_shadow").objectReferenceValue = ChipArt("chip_shadow");
            so.ApplyModifiedPropertiesWithoutUndo();
            EditorUtility.SetDirty(library);
            Debug.Log($"[SceneBootstrap] Chip library populated ({values.Count} colourways).");
        }

        /// <summary>The card template HandView clones. A plain Image, sized at runtime.</summary>
        private static void CreateCardPrefab()
        {
            RectTransform rt = Place(NewRect("CardView", null), Vector2.zero, new Vector2(150f, 210f));
            var image = rt.gameObject.AddComponent<Image>();
            image.preserveAspect = false;
            image.raycastTarget = false;
            image.sprite = RequireAsset<Sprite>($"{CardArtFolder}/card_Back.png");

            GameObject saved = PrefabUtility.SaveAsPrefabAsset(rt.gameObject, CardPrefabPath);
            Object.DestroyImmediate(rt.gameObject);
            if (saved == null) throw new InvalidOperationException($"Could not save prefab to {CardPrefabPath}");
            Debug.Log($"[SceneBootstrap] Built {CardPrefabPath}");
        }

        /// <summary>
        /// The row template StoreUI clones for each chip pack: a glass card with the pack's
        /// chip pile, the amount and bonus, a gold price button, and a BEST VALUE tag.
        /// </summary>
        private static void CreatePackRowPrefab()
        {
            var size = new Vector2(760f, 150f);
            RectTransform root = Place(NewRect("StorePackRow", null), Vector2.zero, size);

            Image shadow = CreateImage(root, "Shadow", Kit("ui_shadow"), new Color(0f, 0f, 0f, 0.5f), Vector2.zero, Vector2.zero);
            StretchInset(shadow.rectTransform, -40f);
            shadow.rectTransform.anchoredPosition = new Vector2(0f, -6f);
            Image fill = CreateShape(root, "Fill", "ui_rrect", Palette.Charcoal.WithAlpha(0.92f), size, 22f);
            Stretch(fill.rectTransform);
            fill.raycastTarget = true;
            Image stroke = CreateShape(root, "Stroke", "ui_rrect_stroke", Palette.Gold.WithAlpha(0.28f), size, 22f);
            Stretch(stroke.rectTransform);
            Image highlight = CreateShape(root, "Highlight", "ui_rrect", Color.white.WithAlpha(0f), size, 22f);
            Stretch(highlight.rectTransform);

            Image chips = CreateImage(root, "ChipArt", ChipArt("pack_0"), Color.white, new Vector2(-size.x / 2f + 96f, 0f), new Vector2(156f, 118f));
            chips.preserveAspect = true;

            // Text starts clear of the widest chip pile.
            TMP_Text amount = Text(root, "Amount", "10,000", TextKind.Value, 44f, Palette.Ivory,
                new Vector2(0f, 16f), new Vector2(320f, 56f), TextAlignmentOptions.Left);
            TMP_Text bonus = Text(root, "Bonus", "+5,000 BONUS", TextKind.Caption, 18f, Palette.Gold,
                new Vector2(0f, -30f), new Vector2(320f, 28f), TextAlignmentOptions.Left, tracking: 3f);

            Image priceFill = CreateShape(root, "PriceButton", "ui_pill", Palette.Gold, new Vector2(168f, 72f), 36f);
            priceFill.rectTransform.anchoredPosition = new Vector2(size.x / 2f - 116f, 0f);
            TMP_Text price = Text(priceFill.transform, "PriceLabel", "$1.99", TextKind.Value, 28f, Palette.Ink,
                Vector2.zero, new Vector2(160f, 60f));
            Stretch(price.rectTransform);

            Image badge = CreateShape(root, "BestValueBadge", "ui_pill", Palette.Gold, new Vector2(150f, 32f), 16f);
            badge.rectTransform.anchoredPosition = new Vector2(-size.x / 2f + 96f, size.y / 2f - 6f);
            TMP_Text badgeText = Text(badge.transform, "Text", "BEST VALUE", TextKind.Caption, 15f, Palette.Ink,
                Vector2.zero, new Vector2(150f, 32f), tracking: 3f);
            Stretch(badgeText.rectTransform);

            var layoutElement = root.gameObject.AddComponent<LayoutElement>();
            layoutElement.preferredHeight = size.y;
            layoutElement.minHeight = size.y;

            var button = root.gameObject.AddComponent<Button>();
            button.targetGraphic = fill;
            button.transition = Selectable.Transition.None;
            var juice = root.gameObject.AddComponent<ButtonJuice>();
            Wire(juice, ("_highlight", highlight));
            SetField(juice, "_hoverScale", 1.01f);

            var row = root.gameObject.AddComponent<StorePackRow>();
            Wire(row,
                ("_button", button),
                ("_chipImage", chips),
                ("_amountLabel", amount),
                ("_bonusLabel", bonus),
                ("_priceLabel", price),
                ("_bestValueBadge", badge.gameObject));

            GameObject saved = PrefabUtility.SaveAsPrefabAsset(root.gameObject, PackRowPrefabPath);
            Object.DestroyImmediate(root.gameObject);
            if (saved == null) throw new InvalidOperationException($"Could not save prefab to {PackRowPrefabPath}");
            Debug.Log($"[SceneBootstrap] Built {PackRowPrefabPath}");
        }

        /// <summary>Human-readable dump of the current wiring — handy when debugging by hand.</summary>
        [MenuItem("Blackjack/Log Scene Wiring Report", priority = 20)]
        private static void LogReport()
        {
            var sb = new StringBuilder("[SceneBootstrap] Wiring report\n");
            List<string> problems = VerifyWiring();
            sb.AppendLine(problems.Count == 0 ? "All serialized references assigned." : string.Join("\n", problems));
            sb.AppendLine("Build Settings:");
            foreach (EditorBuildSettingsScene s in EditorBuildSettings.scenes)
                sb.AppendLine($"  [{(s.enabled ? "x" : " ")}] {s.path}");
            Debug.Log(sb.ToString());
        }
