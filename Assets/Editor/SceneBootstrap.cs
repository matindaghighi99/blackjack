        private static Image CreateImage(Transform parent, string name, Sprite sprite, Color color,
            Vector2 position, Vector2 size, bool raycast = false)
        {
            RectTransform rt = Place(NewRect(name, parent), position, size);
            var image = rt.gameObject.AddComponent<Image>();
            image.sprite = sprite;
            image.color = color;
            image.raycastTarget = raycast;
            if (sprite != null && sprite.border != Vector4.zero)
            {
                image.type = Image.Type.Sliced;
                image.pixelsPerUnitMultiplier = 1f;
            }
            return image;
        }

        /// <summary>A nine-sliced kit shape (rounded rect, pill) with a chosen corner radius.</summary>
        private static Image CreateShape(Transform parent, string name, string sprite, Color color,
            Vector2 size, float cornerRadius)
        {
            Image image = CreateImage(parent, name, Kit(sprite), color, Vector2.zero, size);
            float border = image.sprite.border.x;
            image.type = Image.Type.Sliced;
            // pixelsPerUnitMultiplier scales the rendered border: the sprite's border pixels
            // map to border / multiplier canvas units.
            image.pixelsPerUnitMultiplier = border / Mathf.Max(1f, cornerRadius);
            return image;
        }

