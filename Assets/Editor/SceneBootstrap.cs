        // docs/screenshots/game-table.png is 1024x1536; the game canvas is 1080x1920 with
        // the render scaled to width and pinned 110px down (see extract_table_art.py).
        // Laying the scene out in the render's own pixel coordinates means every element
        // lands exactly where the concept art put it.
        private const float SrcScale = 1080f / 1024f;
        private const float SrcTopPad = 110f;

        private static float SrcX(float x) => x * SrcScale - 540f;
        private static float SrcY(float y) => 960f - (SrcTopPad + y * SrcScale);

