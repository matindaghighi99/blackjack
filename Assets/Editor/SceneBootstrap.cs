        /// <summary>True when a scene on disk predates the current generator.</summary>
        public static bool IsSceneStale(string scenePath)
        {
            if (!File.Exists(scenePath)) return true;
            Match m = Regex.Match(File.ReadAllText(scenePath), @"_sceneBuildVersion: (\d+)");
            return !m.Success || int.Parse(m.Groups[1].Value) != SceneBuildStamp.CurrentVersion;
        }

