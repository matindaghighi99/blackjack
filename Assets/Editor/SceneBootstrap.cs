        /// <summary>
        /// A HandView plus the child transform its cards are parented to. Splitting the
        /// two keeps the layout anchor independent of the component's own transform.
        /// </summary>
        private static HandView CreateHandView(Transform parent, string name, Vector2 position,
            Vector2? cardSize = null)
        {
            GameObject go = NewUIObject(name, parent);
            Place(go, position, new Vector2(960f, 260f));

            GameObject rootGo = NewUIObject("Cards", go.transform);
            Place(rootGo, Vector2.zero, Vector2.zero);

            var view = go.AddComponent<HandView>();
            var prefabGo = AssetDatabase.LoadAssetAtPath<GameObject>(CardPrefabPath);
            if (prefabGo == null)
                throw new InvalidOperationException($"Card prefab missing at {CardPrefabPath}");

            Wire(view,
                ("_library", RequireAsset<CardSpriteLibrary>(CardLibraryPath)),
                ("_cardPrefab", prefabGo.GetComponent<Image>()),
                ("_cardRoot", rootGo.GetComponent<RectTransform>()),
                ("_shadowSprite", UiSprite("card_shadow")));

            if (cardSize.HasValue)
            {
                var so = new SerializedObject(view);
                so.FindProperty("_cardSize").vector2Value = cardSize.Value;
                so.ApplyModifiedPropertiesWithoutUndo();
            }

            return view;
        }

