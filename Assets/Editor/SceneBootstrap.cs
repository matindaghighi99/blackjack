        /// <summary>
        /// Loads an asset that must already exist. Call this immediately before use rather
        /// than caching the reference across a scene load — see the note in BuildMainMenuScene.
        /// </summary>
        private static T RequireAsset<T>(string path) where T : Object
        {
            var asset = AssetDatabase.LoadAssetAtPath<T>(path);
            if (asset == null)
                throw new InvalidOperationException($"Expected a {typeof(T).Name} at '{path}' but could not load it.");
            return asset;
        }

        private static T EnsureAsset<T>(string path) where T : ScriptableObject
        {
            var asset = AssetDatabase.LoadAssetAtPath<T>(path);
            if (asset != null) return asset;

            asset = ScriptableObject.CreateInstance<T>();
            AssetDatabase.CreateAsset(asset, path);
            AssetDatabase.SaveAssets();
            Debug.Log($"[SceneBootstrap] Created {typeof(T).Name} at {path}");
            return asset;
        }

        private static void EnsureFolder(string folder)
        {
            if (AssetDatabase.IsValidFolder(folder)) return;
            string parent = Path.GetDirectoryName(folder)?.Replace('\\', '/');
            string leaf = Path.GetFileName(folder);
            if (string.IsNullOrEmpty(parent) || string.IsNullOrEmpty(leaf)) return;
            EnsureFolder(parent);
            AssetDatabase.CreateFolder(parent, leaf);
        }

        /// <summary>Assigns private [SerializeField] references without needing public setters.</summary>
        private static void Wire(Component target, params (string field, Object value)[] bindings)
        {
            var so = new SerializedObject(target);
            foreach ((string field, Object value) in bindings)
            {
                SerializedProperty prop = so.FindProperty(field);
                if (prop == null)
                    throw new InvalidOperationException(
                        $"{target.GetType().Name} has no serialized field named '{field}'. Did the script change?");
                if (value == null)
                    throw new InvalidOperationException($"{target.GetType().Name}.{field}: nothing to assign (value was null).");
                prop.objectReferenceValue = value;
            }
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void WireArray(Component target, string field, params Object[] values)
        {
            var so = new SerializedObject(target);
            SerializedProperty prop = so.FindProperty(field);
            if (prop == null || !prop.isArray)
                throw new InvalidOperationException($"{target.GetType().Name} has no serialized array '{field}'.");
            prop.arraySize = values.Length;
            for (int i = 0; i < values.Length; i++)
            {
                if (values[i] == null)
                    throw new InvalidOperationException($"{target.GetType().Name}.{field}[{i}]: nothing to assign.");
                prop.GetArrayElementAtIndex(i).objectReferenceValue = values[i];
            }
            so.ApplyModifiedPropertiesWithoutUndo();
        }

        private static void SetField(Component target, string field, object value)
        {
            var so = new SerializedObject(target);
            SerializedProperty prop = so.FindProperty(field);
            if (prop == null)
                throw new InvalidOperationException($"{target.GetType().Name} has no serialized field named '{field}'.");
            switch (value)
            {
                case int i: prop.intValue = i; break;
                case float f: prop.floatValue = f; break;
                case bool b: prop.boolValue = b; break;
                case Vector2 v: prop.vector2Value = v; break;
                case Color c: prop.colorValue = c; break;
                case Object o: prop.objectReferenceValue = o; break;
                default: throw new InvalidOperationException($"Unsupported value for {field}: {value}");
            }
            so.ApplyModifiedPropertiesWithoutUndo();
        }

