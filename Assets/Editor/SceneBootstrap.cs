        private static void BuildGameScene()
        {
            Scene scene = NewScene(out Camera camera);
            GameConfig gameConfig = RequireAsset<GameConfig>(GameConfigPath);

            new GameObject("GameManager").AddComponent<GameManager>();

            Canvas canvas = CreateCanvas(camera);
            CreateTableBackdrop(canvas.transform);
            Transform safe = CreateSafeArea(canvas.transform);
            RectTransform content = Stretch(NewRect("Content", safe));
            var driver = content.gameObject.AddComponent<TableLayoutDriver>();

            // ---- the table itself ------------------------------------------------
            Image lightPool = CreateImage(content, "LightPool", Kit("ui_glow"), LightPoolTint, Vector2.zero, new Vector2(1300f, 1200f));

            var railGo = NewRect("Rail", content).gameObject;
            railGo.AddComponent<CanvasRenderer>();
            var rail = railGo.AddComponent<FeltArc>();
            rail.raycastTarget = false;

            RectTransform printRoot = Stretch(NewRect("FeltPrint", content));
            var printGroup = printRoot.gameObject.AddComponent<CanvasGroup>();
            printGroup.blocksRaycasts = false;
            TMP_Text feltPayout = Text(printRoot, "FeltPayout", "BLACKJACK PAYS 3 TO 2", TextKind.Serif, 40f,
                Palette.Gold.WithAlpha(0.72f), Vector2.zero, new Vector2(1000f, 64f), tracking: 8f);
            feltPayout.gameObject.AddComponent<CurvedText>();
            TMP_Text feltRule = Text(printRoot, "FeltDealerRule", "Dealer hits soft 17", TextKind.SerifItalic, 30f,
                Palette.Gold.WithAlpha(0.58f), Vector2.zero, new Vector2(1000f, 48f), tracking: 1.5f);
            feltRule.gameObject.AddComponent<CurvedText>();

            Image betSpot = CreateImage(content, "BetSpot", Kit("ui_bet_spot"), Palette.Gold.WithAlpha(0.45f), Vector2.zero, new Vector2(250f, 140f));

            RectTransform shoe = CreateShoe(content);
            RectTransform discard = NewRect("Discard", content);

            TotalBadge dealerBadge = CreateTotalBadge(content, "DealerBadge", "DEALER");
            HandView dealerHand = CreateHandView(content, "DealerHandView");

            // Up to four player seats: Classic rules allow re-splits to four hands.
            var seats = new PlayerSeat[4];
            for (int i = 0; i < seats.Length; i++)
                seats[i] = CreateSeat(content, i);

            BetChipView betChip = CreateBetChip(content, out Button betChipButton);
            ResultBanner banner = CreateResultBanner(content);


            TMP_Text statusLabel = Text(content, "StatusLabel", "PLACE YOUR BET", TextKind.Caption, 18f,
                Palette.Ivory.WithAlpha(0.82f), Vector2.zero, new Vector2(900f, 36f), tracking: 5f);
            var statusPunch = statusLabel.gameObject.AddComponent<LabelPunch>();

            // ---- HUD --------------------------------------------------------------
            Image hudBand = CreateImage(content, "HudBand", null, new Color(0.03f, 0.04f, 0.035f, 0.94f), Vector2.zero, Vector2.zero);
            Image hudRule = CreateImage(content, "HudRule", Kit("ui_hairline"), Palette.Gold.WithAlpha(0.5f), Vector2.zero, new Vector2(900f, 2f));
            Button backButton = CreateIconButton(content, "BackButton", "icon_back", 64f, 96f);
            TMP_Text wordmark = Text(content, "Wordmark", "BLACKJACK", TextKind.Wordmark, 40f, Color.white,
                Vector2.zero, new Vector2(520f, 70f), tracking: 13f);
            TMP_Text session = Text(content, "SessionLabel", "", TextKind.Caption, 18f, Palette.Faint,
                Vector2.zero, new Vector2(400f, 40f), TextAlignmentOptions.Left, tracking: 3f);
            Button giftButton = CreateIconButton(content, "QuickGift", "icon_gift", 64f, 96f);
            Button statsButton = CreateIconButton(content, "QuickStats", "icon_stats", 64f, 96f);
            Button settingsButton = CreateIconButton(content, "QuickSettings", "icon_settings", 64f, 96f);
            PulsingDot giftDot = CreateNotificationDot(giftButton, 64f);

            // ---- dock: readouts ------------------------------------------------------
            RectTransform balanceItem = CreateReadout(content, "BalanceReadout", "BALANCE", out TMP_Text balanceCaption, out TMP_Text balanceLabel);
            balanceLabel.name = "BalanceLabel";
            RectTransform betItem = CreateReadout(content, "BetReadout", "BET", out TMP_Text betCaption, out TMP_Text betLabel);
            betLabel.name = "BetLabel";
            RectTransform lastItem = CreateReadout(content, "LastReadout", "LAST", out TMP_Text lastCaption, out TMP_Text lastLabel);
            lastLabel.name = "LastLabel";
            var dividers = new RectTransform[2];
            for (int i = 0; i < dividers.Length; i++)
            {
                Image div = CreateImage(content, $"Divider{i}", Kit("ui_hairline"), Palette.Ivory.WithAlpha(0.18f), Vector2.zero, new Vector2(44f, 2f));
                div.rectTransform.localRotation = Quaternion.Euler(0f, 0f, 90f);
                dividers[i] = div.rectTransform;
            }
            Button addChipsButton = CreateIconButton(content, "AddChipsButton", "icon_plus", 40f, 84f);
            PulsingDot addChipsDot = CreateNotificationDot(addChipsButton, 40f, "OutOfChipsDot");
            addChipsDot.gameObject.SetActive(false);

            // ---- dock: bet row -------------------------------------------------------
            CanvasGroup betRow = CreateRow(content, "BetRow");
            int[] denominations = gameConfig.ChipDenominations != null && gameConfig.ChipDenominations.Length > 0
                ? gameConfig.ChipDenominations
                : new[] { 10, 25, 100, 500, 1000 };
            int rack = Mathf.Clamp(denominations.Length, 1, 7);
            var chipButtons = new ChipButton[rack];
            var chipRawButtons = new Button[rack];
            for (int i = 0; i < rack; i++)
            {
                chipButtons[i] = CreateChipButton(betRow.transform, denominations[Mathf.Min(i, denominations.Length - 1)]);
                chipRawButtons[i] = chipButtons[i].GetComponent<Button>();
            }
            Button clearButton = CreateIconButton(betRow.transform, "ClearButton", "icon_undo", 52f, 72f);
            Button dealButton = CreateTextButton(betRow.transform, "DealButton", "DEAL", ButtonStyle.Gold,
                Vector2.zero, new Vector2(300f, 116f), primaryGlow: true);

            // ---- dock: action row ----------------------------------------------------
            // HIT and STAND are the decisions made on nearly every hand, so they are the two
            // filled buttons; DOUBLE and SPLIT (which commit more chips) are glass and show
            // the extra stake underneath.
            CanvasGroup actionRow = CreateRow(content, "ActionRow");
            Button doubleButton = CreateTextButton(actionRow.transform, "DoubleButton", "DOUBLE", ButtonStyle.Glass,
                Vector2.zero, new Vector2(180f, 104f), subLabel: "+0");
            Button hitButton = CreateTextButton(actionRow.transform, "HitButton", "HIT", ButtonStyle.Gold,
                Vector2.zero, new Vector2(280f, 116f));
            Button standButton = CreateTextButton(actionRow.transform, "StandButton", "STAND", ButtonStyle.Ivory,
                Vector2.zero, new Vector2(280f, 116f));
            Button splitButton = CreateTextButton(actionRow.transform, "SplitButton", "SPLIT", ButtonStyle.Glass,
                Vector2.zero, new Vector2(180f, 104f), subLabel: "+0");
            Button surrenderButton = CreateTextButton(actionRow.transform, "SurrenderButton", "SURRENDER", ButtonStyle.Glass,
                Vector2.zero, new Vector2(160f, 104f));
            surrenderButton.gameObject.SetActive(false);

            SettingsPanel settingsPanel = CreateSettingsPanel(content);
            StatsPanel statsPanel = CreateStatsPanel(content);
            CreateFader(canvas.transform);

            var balanceRollup = balanceLabel.gameObject.AddComponent<CountRollup>();

            // ---- layout driver ---------------------------------------------------------
            Wire(driver,
                ("_root", content),
                ("_hudBand", hudBand.rectTransform),
                ("_hudRule", hudRule.rectTransform),
                ("_backButton", (RectTransform)backButton.transform),
                ("_wordmark", wordmark),
                ("_session", session),
                ("_rail", rail),
                ("_shoe", shoe),
                ("_discard", discard),
                ("_dealerHand", dealerHand),
                ("_dealerBadge", (RectTransform)dealerBadge.transform),
                ("_feltPrimary", feltPayout),
                ("_feltSecondary", feltRule),
                ("_banner", banner),
                ("_betSpot", betSpot.rectTransform),
                ("_betChip", betChip),
                ("_status", statusLabel.rectTransform),
                ("_lightPool", lightPool.rectTransform),
                ("_deal", (RectTransform)dealButton.transform),
                ("_addChips", (RectTransform)addChipsButton.transform),
                ("_clearBet", (RectTransform)clearButton.transform));
            WireArray(driver, "_hudIcons", (RectTransform)settingsButton.transform,
                (RectTransform)statsButton.transform, (RectTransform)giftButton.transform);
            WireArray(driver, "_chips", chipButtons);
            WireArray(driver, "_actions", (RectTransform)doubleButton.transform, (RectTransform)hitButton.transform,
                (RectTransform)standButton.transform, (RectTransform)splitButton.transform, (RectTransform)surrenderButton.transform);
            WireArray(driver, "_stripItems", balanceItem, betItem, lastItem);
            WireArray(driver, "_stripCaptions", balanceCaption, betCaption, lastCaption);
            WireArray(driver, "_stripValues", balanceLabel, betLabel, lastLabel);
            WireArray(driver, "_stripDividers", dividers);

            // ---- the screen ---------------------------------------------------------------
            var ui = canvas.gameObject.AddComponent<GameTableUI>();
            Wire(ui,
                ("_layout", driver),
                ("_chipLibrary", RequireAsset<ChipSpriteLibrary>(ChipLibraryPath)),
                ("_dealButton", dealButton),
                ("_clearButton", clearButton),
                ("_betChip", betChip),
                ("_betChipButton", betChipButton),
                ("_betRow", betRow),
                ("_actionRow", actionRow),
                ("_hitButton", hitButton),
                ("_standButton", standButton),
                ("_doubleButton", doubleButton),
                ("_splitButton", splitButton),
                ("_surrenderButton", surrenderButton),
                ("_doubleCost", FindChildText(doubleButton, "SubLabel")),
                ("_splitCost", FindChildText(splitButton, "SubLabel")),
                ("_dealerHandView", dealerHand),
                ("_dealerBadge", dealerBadge),
                ("_shoe", shoe),
                ("_discard", discard),
                ("_feltPrint", printGroup),
                ("_feltPayout", feltPayout),
                ("_feltDealerRule", feltRule),
                ("_sessionLabel", session),
                ("_banner", banner),
                ("_balanceLabel", balanceLabel),
                ("_balanceRollup", balanceRollup),
                ("_betLabel", betLabel),
                ("_lastLabel", lastLabel),
                ("_statusLabel", statusLabel),
                ("_statusPunch", statusPunch),
                ("_backButton", backButton),
                ("_addChipsButton", addChipsButton),
                ("_addChipsDot", addChipsDot),
                ("_giftButton", giftButton),
                ("_giftDot", giftDot),
                ("_settingsButton", settingsButton),
                ("_statsButton", statsButton),
                ("_settingsPanel", settingsPanel),
                ("_statsPanel", statsPanel));
            WireArray(ui, "_chipButtons", chipButtons);
            WireArray(ui, "_seats", seats);

            KeyboardNavigator navigator = AddKeyboard(canvas, dealButton, settingsPanel.gameObject, statsPanel.gameObject);
            SetField(ui, "_navigator", navigator);

            var shortcuts = canvas.gameObject.AddComponent<TableShortcuts>();
            Wire(shortcuts,
                ("_navigator", navigator),
                ("_deal", dealButton),
                ("_hit", hitButton),
                ("_stand", standButton),
                ("_double", doubleButton),
                ("_split", splitButton),
                ("_surrender", surrenderButton),
                ("_clear", clearButton));
            WireArray(shortcuts, "_chips", chipRawButtons);

            // Bake a portrait preview so the scene reads correctly in the editor; the
            // driver re-lays everything out for the real screen on Start.
            driver.Apply(ReferenceResolution);
            TableLayout preview = driver.Current;
            SeatLayout one = preview.Seats(1);
            TableLayoutDriver.Place((RectTransform)seats[0].transform, one.Xs[0], one.Y, 10f, 10f);
            for (int i = 1; i < seats.Length; i++)
                TableLayoutDriver.Place((RectTransform)seats[i].transform, one.Xs[0], one.Y, 10f, 10f);
            driver.PlaceBetSpot(one.Bet, true);

            Stamp(canvas);
            SaveScene(scene, GameScenePath);
        }

