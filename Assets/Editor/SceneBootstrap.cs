    /// <summary>
    /// One-shot project bootstrapper. Builds the three UI scenes from scratch and wires
    /// every <c>[SerializeField]</c> reference programmatically, so the scenes are
    /// reproducible from source instead of hand-assembled in the editor.
    ///
    /// Run it from the menu (<b>Blackjack ▸ Build UI Scenes</b>) or headlessly:
    /// <code>
    /// Unity.exe -batchmode -projectPath "&lt;root&gt;" -logFile - \
    ///           -executeMethod BlackjackGame.EditorTools.SceneBootstrap.BuildAllFromCommandLine
    /// </code>
    /// It is idempotent: re-running overwrites the scenes and reuses existing config assets.
    /// </summary>
    public static class SceneBootstrap
    {
        // ---- Paths ----
        private const string ScenesFolder = "Assets/Scenes";
        private const string SettingsFolder = "Assets/Settings";
        private const string PrefabsFolder = "Assets/Prefabs";

        private const string MainMenuScenePath = ScenesFolder + "/MainMenu.unity";
        private const string GameScenePath = ScenesFolder + "/Game.unity";
        private const string StoreScenePath = ScenesFolder + "/Store.unity";

        private const string GameConfigPath = SettingsFolder + "/GameConfig.asset";
        private const string EconomyConfigPath = SettingsFolder + "/EconomyConfig.asset";
        private const string PackRowPrefabPath = PrefabsFolder + "/StorePackRow.prefab";
        private const string CardPrefabPath = PrefabsFolder + "/CardView.prefab";
        private const string CardLibraryPath = SettingsFolder + "/CardSpriteLibrary.asset";

        // Art generated by art-source/generate_card_art.py
        private const string CardArtFolder = "Assets/Art/Cards";
        private const string FeltSpritePath = "Assets/Art/Table/Felt.png";

        // Gold UI kit generated by art-source/generate_ui_kit.py
        private const string UiArtFolder = "Assets/Art/UI";

        // Table plate + sprites lifted from the concept render by
        // art-source/extract_table_art.py
        private const string TableBackgroundPath = "Assets/Art/Table/TableBackground.png";
        private const string StoreBackgroundPath = "Assets/Art/Table/StoreBackground.png";
        private const string MenuBackgroundPath = "Assets/Art/Table/MenuBackground.png";

        // ---- Concept-render coordinate mapping -------------------------------
        // docs/screenshots/game-table.png is 1024x1536; the game canvas is 1080x1920 with
        // the render scaled to width and pinned 110px down (see extract_table_art.py).
        // Laying the scene out in the render's own pixel coordinates means every element
        // lands exactly where the concept art put it.
        private const float SrcScale = 1080f / 1024f;
        private const float SrcTopPad = 110f;

        private static float SrcX(float x) => x * SrcScale - 540f;
        private static float SrcY(float y) => 960f - (SrcTopPad + y * SrcScale);

        // ---- Palette ----
        private static readonly Color Felt = new Color(0.043f, 0.180f, 0.129f);
        private static readonly Color Panel = new Color(0.031f, 0.129f, 0.094f);
        /// <summary>Panels over the felt art — translucent so the table reads through.</summary>
        private static readonly Color GlassPanel = new Color(0.016f, 0.086f, 0.063f, 0.55f);
        private static readonly Color Gold = new Color(0.949f, 0.769f, 0.310f);
        private static readonly Color ButtonFill = new Color(0.129f, 0.353f, 0.263f);
        private static readonly Color ButtonAccent = new Color(0.729f, 0.180f, 0.180f);
        private static readonly Color Ink = new Color(0.918f, 0.945f, 0.933f);

        // Glow colours for the table actions. Each is a brightened version of its own
        // button frame so the halo reads as that button lighting up, not as a stray
        // coloured rim — a gold glow on a red frame just looks like a rendering mistake.
        private static readonly Color HitGlow = new Color(0.42f, 1.00f, 0.52f);
        private static readonly Color StandGlow = new Color(1.00f, 0.44f, 0.40f);
        private static readonly Color DoubleGlow = new Color(0.44f, 0.72f, 1.00f);
        private static readonly Color SplitGlow = new Color(1.00f, 0.84f, 0.42f);

        private static readonly Vector2 ReferenceResolution = new Vector2(1080f, 1920f);

        // =====================================================================
        //  Entry points
