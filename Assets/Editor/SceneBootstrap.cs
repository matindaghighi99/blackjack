        /// <summary>
        /// The shared button: soft shadow, fill, optional hairline, hover highlight, label
        /// (and sub-label), keyboard focus ring, optional breathing glow — all driven by
        /// ButtonJuice. Children stretch, so the layout can resize the button freely.
        /// </summary>
        private static Button CreateTextButton(Transform parent, string name, string label, ButtonStyle style,
            Vector2 position, Vector2 size, string subLabel = null, bool primaryGlow = false)
        {
            RectTransform root = Place(NewRect(name, parent), position, size);
            const float radius = 20f;

            Image glow = null;
            if (primaryGlow)
            {
                glow = CreateImage(root, "Glow", Kit("ui_glow"), Palette.Gold.WithAlpha(0f), Vector2.zero, Vector2.zero);
                StretchInset(glow.rectTransform, -46f);
            }

            Image shadow = CreateImage(root, "Shadow", Kit("ui_shadow"), new Color(0f, 0f, 0f, 0.55f), Vector2.zero, Vector2.zero);
            StretchInset(shadow.rectTransform, -44f);
            shadow.rectTransform.anchoredPosition = new Vector2(0f, -8f);

            Color fillColor = style == ButtonStyle.Gold ? Palette.Gold
                : style == ButtonStyle.Ivory ? Palette.Ivory
                : Palette.Glass.WithAlpha(0.86f);
            Image fill = CreateShape(root, "Fill", "ui_rrect", fillColor, size, radius);
            Stretch(fill.rectTransform);
            fill.raycastTarget = true;

            if (style == ButtonStyle.Glass)
            {
                Image stroke = CreateShape(root, "Stroke", "ui_rrect_stroke", Palette.Gold.WithAlpha(0.55f), size, radius);
                Stretch(stroke.rectTransform);
            }

            Image highlight = CreateShape(root, "Highlight", "ui_rrect", Color.white.WithAlpha(0f), size, radius);
            Stretch(highlight.rectTransform);

            Color ink = style == ButtonStyle.Glass ? Palette.Ivory : Palette.Ink;
            float labelSize = size.y >= 110f ? 30f : 26f;
            TMP_Text text = Text(root, "Label", label, TextKind.Label, labelSize, ink,
                new Vector2(0f, subLabel != null ? 12f : 0f), new Vector2(size.x - 16f, 44f), tracking: 3.5f);
            StretchHorizontally(text.rectTransform, 8f);
            if (subLabel != null)
            {
                TMP_Text sub = Text(root, "SubLabel", subLabel, TextKind.Caption, 19f,
                    style == ButtonStyle.Glass ? Palette.Muted : ink, new Vector2(0f, -22f), new Vector2(size.x - 16f, 28f),
                    tracking: 1.5f);
                StretchHorizontally(sub.rectTransform, 8f);
            }

            Image focus = CreateShape(root, "FocusRing", "ui_focus_ring", Palette.GoldLight.WithAlpha(0f), size, radius + 12f);
            StretchInset(focus.rectTransform, -12f);

            var button = root.gameObject.AddComponent<Button>();
            button.targetGraphic = fill;
            button.transition = Selectable.Transition.None;

            var juice = root.gameObject.AddComponent<ButtonJuice>();
            Wire(juice, ("_highlight", highlight), ("_focusRing", focus));
            if (glow != null) SetField(juice, "_glow", glow);
            return button;
        }

        private static void StretchHorizontally(RectTransform rt, float inset)
        {
            float y = rt.anchoredPosition.y;
            float h = rt.sizeDelta.y;
            rt.anchorMin = new Vector2(0f, 0.5f);
            rt.anchorMax = new Vector2(1f, 0.5f);
            rt.pivot = new Vector2(0.5f, 0.5f);
            rt.offsetMin = new Vector2(inset, y - h / 2f);
            rt.offsetMax = new Vector2(-inset, y + h / 2f);
        }

