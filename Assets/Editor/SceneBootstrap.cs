        /// <summary>
        /// Removes the label/title sprites that used to carry the gold text. They were
        /// replaced by live TextMeshPro, which is sharp at any size and can't be scaled
        /// wrong — the old sprites shipped their glyphs inside ~26px of transparent
        /// padding, so sizing by sprite height silently shrank the text.
        /// Goes through AssetDatabase so the .meta files go with them.
        /// </summary>
        private static void DeleteObsoleteBakedLabels()
        {
            if (!AssetDatabase.IsValidFolder(UiArtFolder)) return;

            int removed = 0;
            foreach (string guid in AssetDatabase.FindAssets("t:Texture2D", new[] { UiArtFolder }))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                string file = Path.GetFileName(path);
                if (file.StartsWith("label_", StringComparison.Ordinal) ||
                    file.StartsWith("title_", StringComparison.Ordinal))
                {
                    if (AssetDatabase.DeleteAsset(path)) removed++;
                }
            }

            // chip_stack was first written to Assets/Art/Table; it belongs with the kit.
            if (AssetDatabase.DeleteAsset("Assets/Art/Table/chip_stack.png")) removed++;

            if (removed > 0)
                Debug.Log($"[SceneBootstrap] Removed {removed} obsolete sprite(s).");
        }

        /// <summary>Loads a kit sprite by bare name; ".b&lt;N&gt;" nine-slice files resolve too.</summary>
        private static Sprite UiSprite(string name)
        {
            var sprite = AssetDatabase.LoadAssetAtPath<Sprite>($"{UiArtFolder}/{name}.png");
            if (sprite != null) return sprite;

            // Try the nine-sliced variants, whose filenames carry a border suffix.
            foreach (string guid in AssetDatabase.FindAssets($"{name} t:Sprite", new[] { UiArtFolder }))
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                if (Path.GetFileName(path).StartsWith(name + ".b", StringComparison.Ordinal))
                    return AssetDatabase.LoadAssetAtPath<Sprite>(path);
            }

            throw new InvalidOperationException(
                $"UI sprite '{name}' not found in {UiArtFolder}. " +
                "Run 'python3 art-source/generate_ui_kit.py' from the project root.");
        }

        /// <summary>A nine-sliced frame (button background, pill, panel).</summary>
        private static Image CreateFrame(Transform parent, string name, string sprite,
            Vector2 position, Vector2 size)
        {
            GameObject go = NewUIObject(name, parent);
            Place(go, position, size);
            var image = go.AddComponent<Image>();
            image.sprite = UiSprite(sprite);
            image.type = Image.Type.Sliced;
            image.pixelsPerUnitMultiplier = 1f;
            image.raycastTarget = false;
            return image;
        }

        /// <summary>
        /// An icon or baked-label sprite. Give it a target height, or pass
        /// <paramref name="widthOverride"/> to size by width instead — the other
        /// dimension follows the sprite's aspect either way.
        /// </summary>
        private static Image CreateSpriteImage(Transform parent, string name, string sprite,
            Vector2 position, float height, float widthOverride = 0f)
        {
            Sprite s = UiSprite(sprite);
            float aspect = s.rect.width / s.rect.height;

            float width;
            if (widthOverride > 0f)
            {
                width = widthOverride;
                height = width / aspect;
            }
            else
            {
                width = height * aspect;
            }

            GameObject go = NewUIObject(name, parent);
            Place(go, position, new Vector2(width, height));
            var image = go.AddComponent<Image>();
            image.sprite = s;
            image.type = Image.Type.Simple;
            image.preserveAspect = true;
            image.raycastTarget = false;
            return image;
        }

        /// <summary>A button whose background is a nine-sliced gold frame.</summary>
        private static Button CreateFrameButton(Transform parent, string name, string sprite,
            Vector2 position, Vector2 size)
        {
            GameObject go = NewUIObject(name, parent);
            Place(go, position, size);

            var image = go.AddComponent<Image>();
            image.sprite = UiSprite(sprite);
            image.type = Image.Type.Sliced;
            image.pixelsPerUnitMultiplier = 1f;

            var button = go.AddComponent<Button>();
            button.targetGraphic = image;

            ColorBlock colors = button.colors;
            colors.normalColor = Color.white;
            colors.highlightedColor = new Color(1.10f, 1.10f, 1.10f, 1f);
            colors.pressedColor = new Color(0.80f, 0.80f, 0.80f, 1f);
            // Distinctly dimmer + desaturated so unavailable actions read at a glance.
            colors.disabledColor = new Color(0.42f, 0.44f, 0.42f, 0.75f);
            colors.fadeDuration = 0.08f;
            button.colors = colors;

            return button;
        }

