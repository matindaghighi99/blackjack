        /// <summary>
        /// Opens each scene and reports any serialized object reference that was left null,
        /// plus any missing scene/build-settings entry. Empty list == fully wired.
        /// </summary>
        public static List<string> VerifyWiring()
        {
            var problems = new List<string>();

            CheckScene(MainMenuScenePath, problems, typeof(AppManager), typeof(MainMenuUI),
                typeof(SettingsPanel), typeof(StatsPanel));
            CheckScene(GameScenePath, problems, typeof(GameManager), typeof(GameTableUI), typeof(HandView),
                typeof(SettingsPanel), typeof(StatsPanel));
            CheckScene(StoreScenePath, problems, typeof(StoreUI), typeof(SettingsPanel), typeof(StatsPanel));

            // The card faces live in an array, which the per-field scan below cannot see.
            var library = AssetDatabase.LoadAssetAtPath<CardSpriteLibrary>(CardLibraryPath);
            if (library == null) problems.Add($"Missing CardSpriteLibrary at {CardLibraryPath}.");
            else if (!library.IsComplete)
                problems.Add("CardSpriteLibrary is incomplete — some faces or the back are unassigned.");

            if (AssetDatabase.LoadAssetAtPath<GameObject>(CardPrefabPath) == null)
                problems.Add($"Missing card prefab at {CardPrefabPath}.");
            if (AssetDatabase.LoadAssetAtPath<GameObject>(PackRowPrefabPath) == null)
                problems.Add($"Missing store row prefab at {PackRowPrefabPath}.");
            if (AssetDatabase.LoadAssetAtPath<Sprite>(FeltSpritePath) == null)
                problems.Add($"Missing table felt sprite at {FeltSpritePath}.");

            foreach (string path in new[]
                     {
                         FontAssetBuilder.DisplayAssetPath, FontAssetBuilder.BodyBoldAssetPath,
                         FontAssetBuilder.BodyAssetPath, FontAssetBuilder.GoldMaterialPath,
                         FontAssetBuilder.GoldSmallMaterialPath, FontAssetBuilder.InkMaterialPath,
                         FontAssetBuilder.GoldGradientPath,
                     })
            {
                if (AssetDatabase.LoadAssetAtPath<Object>(path) == null)
                    problems.Add($"Missing font asset '{path}' — run Blackjack ▸ Rebuild Font Assets.");
            }

            string[] expected = { MainMenuScenePath, GameScenePath, StoreScenePath };
            EditorBuildSettingsScene[] registered = EditorBuildSettings.scenes;
            for (int i = 0; i < expected.Length; i++)
            {
                if (i >= registered.Length || registered[i].path != expected[i] || !registered[i].enabled)
                {
                    problems.Add($"Build Settings slot {i} should be an enabled '{expected[i]}'.");
                }
            }

            return problems;
        }

        private static void CheckScene(string scenePath, List<string> problems, params Type[] requiredComponents)
        {
            if (AssetDatabase.LoadAssetAtPath<SceneAsset>(scenePath) == null)
            {
                problems.Add($"Scene missing: {scenePath}");
                return;
            }

            Scene scene = EditorSceneManager.OpenScene(scenePath, OpenSceneMode.Single);

            foreach (Type type in requiredComponents)
            {
                // Include inactive: SettingsPanel/StatsPanel start deactivated (they're
                // modals hidden until Show() is called), and the default overload only
                // finds active objects — without this every fresh build "fails" wiring
                // verification despite being wired correctly.
                var found = Object.FindObjectsByType(type, FindObjectsInactive.Include, FindObjectsSortMode.None);
                if (found.Length == 0)
                {
                    problems.Add($"{scene.name}: no {type.Name} in the scene.");
                    continue;
                }

                foreach (Object o in found)
                {
                    if (o is Component component) CollectUnassignedFields(component, scene.name, problems);
                }
            }

            if (Object.FindFirstObjectByType<EventSystem>() == null)
                problems.Add($"{scene.name}: no EventSystem (UI would be unclickable).");
            if (Object.FindFirstObjectByType<Canvas>() == null)
                problems.Add($"{scene.name}: no Canvas.");
        }

        private static void CollectUnassignedFields(Component component, string sceneName, List<string> problems)
        {
            var so = new SerializedObject(component);
            SerializedProperty it = so.GetIterator();
            bool enterChildren = true;
            while (it.NextVisible(enterChildren))
            {
                enterChildren = false;
                if (it.propertyType != SerializedPropertyType.ObjectReference) continue;
                if (it.objectReferenceValue == null)
                    problems.Add($"{sceneName}: {component.GetType().Name}.{it.propertyPath} is not assigned.");
            }
        }

