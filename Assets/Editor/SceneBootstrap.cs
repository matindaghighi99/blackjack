        /// <summary>
        /// The three text treatments in the game. Baked label sprites used to do this job;
        /// TMP does it live, stays sharp at any size, and can't get its scale wrong.
        /// </summary>
        public enum TextStyle
        {
            /// <summary>Serif display face, metallic gold, bevelled — titles and button labels.</summary>
            DisplayGold,
            /// <summary>Bold body face in gold — subtitles, house rules.</summary>
            BodyGold,
            /// <summary>Plain body face in warm off-white — status lines, disclaimers.</summary>
            BodyInk,
        }

        private static T RequireFontAsset<T>(string path) where T : Object
        {
            var asset = AssetDatabase.LoadAssetAtPath<T>(path);
            if (asset == null)
                throw new InvalidOperationException(
                    $"Missing '{path}'. Run Blackjack ▸ Rebuild Font Assets first.");
            return asset;
        }

        private static TMP_Text CreateText(
            Transform parent,
            string name,
            string content,
            Vector2 position,
            Vector2 size,
            float fontSize,
            TextAlignmentOptions alignment = TextAlignmentOptions.Center,
            TextStyle style = TextStyle.BodyInk,
            float characterSpacing = 0f,
            bool wrap = false)
        {
            GameObject go = NewUIObject(name, parent);
            Place(go, position, size);

            var text = go.AddComponent<TextMeshProUGUI>();
            text.text = content;
            text.fontSize = fontSize;
            text.alignment = alignment;
            text.characterSpacing = characterSpacing;
            text.raycastTarget = false;
            text.textWrappingMode = wrap ? TextWrappingModes.Normal : TextWrappingModes.NoWrap;
            text.overflowMode = TextOverflowModes.Overflow;

            switch (style)
            {
                case TextStyle.DisplayGold:
                    text.font = RequireFontAsset<TMP_FontAsset>(FontAssetBuilder.DisplayAssetPath);
                    text.fontSharedMaterial = RequireFontAsset<Material>(FontAssetBuilder.GoldMaterialPath);
                    text.colorGradientPreset =
                        RequireFontAsset<TMP_ColorGradient>(FontAssetBuilder.GoldGradientPath);
                    text.enableVertexGradient = true;
                    break;

                case TextStyle.BodyGold:
                    text.font = RequireFontAsset<TMP_FontAsset>(FontAssetBuilder.BodyBoldAssetPath);
                    text.fontSharedMaterial = RequireFontAsset<Material>(FontAssetBuilder.GoldSmallMaterialPath);
                    text.colorGradientPreset =
                        RequireFontAsset<TMP_ColorGradient>(FontAssetBuilder.GoldGradientPath);
                    text.enableVertexGradient = true;
                    break;

                default:
                    text.font = RequireFontAsset<TMP_FontAsset>(FontAssetBuilder.BodyAssetPath);
                    text.fontSharedMaterial = RequireFontAsset<Material>(FontAssetBuilder.InkMaterialPath);
                    break;
            }

            return text;
        }

        private static Button CreateButton(
            Transform parent,
            string name,
            string label,
            Vector2 position,
            Vector2 size,
            Color fill)
        {
            GameObject go = NewUIObject(name, parent);
            Place(go, position, size);

            var image = go.AddComponent<Image>();
            image.color = fill;

            var button = go.AddComponent<Button>();
            button.targetGraphic = image;

            ColorBlock colors = button.colors;
            colors.highlightedColor = Color.Lerp(fill, Color.white, 0.15f);
            colors.pressedColor = Color.Lerp(fill, Color.black, 0.2f);
            colors.disabledColor = new Color(fill.r, fill.g, fill.b, 0.35f);
            button.colors = colors;

            CreateText(go.transform, "Label", label, Vector2.zero,
                new Vector2(size.x - 16f, size.y - 16f),
                Mathf.Min(size.y * 0.34f, 52f), TextAlignmentOptions.Center,
                TextStyle.DisplayGold, characterSpacing: 2f);

            return button;
        }

        private static TMP_InputField CreateInputField(
            Transform parent,
            string name,
            string defaultValue,
            Vector2 position,
            Vector2 size)
        {
            GameObject go = NewUIObject(name, parent);
            Place(go, position, size);

            var background = go.AddComponent<Image>();
            background.sprite = UiSprite("pill");
            background.type = Image.Type.Sliced;
            background.pixelsPerUnitMultiplier = 1f;

            var input = go.AddComponent<TMP_InputField>();
            input.targetGraphic = background;
            input.contentType = TMP_InputField.ContentType.IntegerNumber;
            input.characterLimit = 9;

            // TMP_InputField needs its text area to be a child RectTransform with a mask,
            // otherwise the caret and text render outside the field.
            GameObject viewport = NewUIObject("Text Area", go.transform);
            Stretch(viewport, 22f);
            viewport.AddComponent<RectMask2D>();

            TMP_Text placeholder = CreateText(viewport.transform, "Placeholder", "Bet…",
                Vector2.zero, size - new Vector2(44f, 44f), 44f,
                TextAlignmentOptions.Center, TextStyle.BodyInk);
            placeholder.fontStyle = FontStyles.Italic;
            placeholder.color = new Color(0.78f, 0.76f, 0.68f, 0.7f);
            Stretch(placeholder.gameObject);

            TMP_Text text = CreateText(viewport.transform, "Text", string.Empty,
                Vector2.zero, size - new Vector2(44f, 44f), 48f,
                TextAlignmentOptions.Center, TextStyle.BodyGold);
            text.richText = false;
            Stretch(text.gameObject);

            input.textViewport = (RectTransform)viewport.transform;
            input.textComponent = text;
            input.placeholder = placeholder;
            input.text = defaultValue;

            return input;
        }

        /// <summary>
        /// Fills the CardSpriteLibrary asset from Assets/Art/Cards. File names encode the
        /// suit and rank so the mapping is mechanical: card_&lt;Suit&gt;_&lt;01..13&gt;.png,
        /// with Suit spelled exactly as the C# enum.
        /// </summary>
        private static void PopulateCardLibrary()
        {
            CardSpriteLibrary library = RequireAsset<CardSpriteLibrary>(CardLibraryPath);
            var so = new SerializedObject(library);

            SerializedProperty faces = so.FindProperty("_faces");
            faces.arraySize = CardSpriteLibrary.FaceCount;

            var missing = new List<string>();
            foreach (Suit suit in (Suit[])Enum.GetValues(typeof(Suit)))
            {
                for (int rank = 1; rank <= 13; rank++)
                {
                    string path = $"{CardArtFolder}/card_{suit}_{rank:00}.png";
                    var sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path);
                    if (sprite == null) missing.Add(path);

                    int index = CardSpriteLibrary.IndexOf(new Card(suit, (Rank)rank));
                    faces.GetArrayElementAtIndex(index).objectReferenceValue = sprite;
                }
            }

            var back = AssetDatabase.LoadAssetAtPath<Sprite>($"{CardArtFolder}/card_Back.png");
            if (back == null) missing.Add($"{CardArtFolder}/card_Back.png");
            so.FindProperty("_back").objectReferenceValue = back;

            so.ApplyModifiedPropertiesWithoutUndo();
            EditorUtility.SetDirty(library);

            if (missing.Count > 0)
            {
                throw new InvalidOperationException(
                    $"{missing.Count} card sprite(s) missing, first: {missing[0]}. " +
                    "Run 'python3 art-source/generate_card_art.py' from the project root. " +
                    "If the PNGs exist, they may have imported as Textures rather than " +
                    "Sprites — ArtImportSettings should prevent that.");
            }

            Debug.Log($"[SceneBootstrap] Card library populated ({CardSpriteLibrary.FaceCount} faces + back).");
        }

