        public static void BuildAll()
        {
            EnsureFolder(ScenesFolder);
            EnsureFolder(SettingsFolder);
            EnsureFolder(PrefabsFolder);

            DeleteObsoleteBakedLabels();

            // Text is TextMeshPro now, so the font assets and gold materials have to exist
            // before any scene is built. Cheap no-op once they're there.
            if (AssetDatabase.LoadAssetAtPath<TMP_FontAsset>(FontAssetBuilder.DisplayAssetPath) == null)
                FontAssetBuilder.BuildAll();

            // Only guarantees the assets exist on disk. Do NOT hold the returned
            // references across a scene change — see RequireAsset below.
            EnsureAsset<GameConfig>(GameConfigPath);
            EnsureAsset<EconomyConfig>(EconomyConfigPath);
            EnsureAsset<CardSpriteLibrary>(CardLibraryPath);
            PopulateCardLibrary();
            CreateCardPrefab();

            BuildMainMenuScene();
            BuildGameScene();
            BuildStoreScene();

            RegisterBuildSettingsScenes();

            AssetDatabase.SaveAssets();
            AssetDatabase.Refresh();
        }

