    /// <summary>
    /// Offers to rebuild the UI scenes when the ones on disk were generated by an older
    /// version of <see cref="SceneBootstrap"/> — e.g. right after pulling a UI change —
    /// so nobody ends up testing a stale layout against new scripts.
    /// </summary>
    [InitializeOnLoad]
    internal static class StaleSceneCheck
    {
        private const string AskedKey = "Blackjack.StaleSceneCheck.Asked";

        static StaleSceneCheck()
        {
            EditorApplication.delayCall += Check;
        }

        private static void Check()
        {
            if (Application.isBatchMode || EditorApplication.isPlayingOrWillChangePlaymode) return;
            if (SessionState.GetBool(AskedKey, false)) return;
            SessionState.SetBool(AskedKey, true);

            bool stale = SceneBootstrap.IsSceneStale(SceneBootstrap.GameScenePath) ||
                         SceneBootstrap.IsSceneStale(SceneBootstrap.MainMenuScenePath) ||
                         SceneBootstrap.IsSceneStale(SceneBootstrap.StoreScenePath);
            if (!stale) return;

            if (EditorUtility.DisplayDialog("Blackjack",
                    "The UI scenes were generated by an older version of the scene bootstrapper and " +
                    "don't match the current scripts. Rebuild them now?\n\n(Same as Blackjack ▸ Build UI Scenes.)",
                    "Rebuild", "Later"))
            {
                SceneBootstrap.BuildAll();
            }
        }
    }
