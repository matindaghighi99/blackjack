        /// <summary>
        /// An icon or baked-label sprite. Give it a target height, or pass
        /// <paramref name="widthOverride"/> to size by width instead — the other
        /// dimension follows the sprite's aspect either way.
        /// </summary>
        private static Image CreateSpriteImage(Transform parent, string name, string sprite,
            Vector2 position, float height, float widthOverride = 0f)
        {
            Sprite s = UiSprite(sprite);
            float aspect = s.rect.width / s.rect.height;

            float width;
            if (widthOverride > 0f)
            {
                width = widthOverride;
                height = width / aspect;
            }
            else
            {
                width = height * aspect;
            }

            GameObject go = NewUIObject(name, parent);
            Place(go, position, new Vector2(width, height));
            var image = go.AddComponent<Image>();
            image.sprite = s;
            image.type = Image.Type.Simple;
            image.preserveAspect = true;
            image.raycastTarget = false;
            return image;
        }

