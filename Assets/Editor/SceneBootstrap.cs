        /// (converted to TMP's em/100), so tracking reads the same at any size.
        /// </summary>
        private static TMP_Text Text(Transform parent, string name, string content, TextKind kind, float size,
            Color color, Vector2 position, Vector2 box,
            TextAlignmentOptions alignment = TextAlignmentOptions.Center, float tracking = 0f)
        {
            RectTransform rt = Place(NewRect(name, parent), position, box);
            var text = rt.gameObject.AddComponent<TextMeshProUGUI>();
            text.text = content;
            text.fontSize = size;
            text.alignment = alignment;
            text.characterSpacing = tracking / Mathf.Max(1f, size) * 100f;
            text.raycastTarget = false;
            text.textWrappingMode = TextWrappingModes.NoWrap;
            text.overflowMode = TextOverflowModes.Overflow;
            text.richText = false;

            string fontPath;
            switch (kind)
            {
                case TextKind.Wordmark:
                case TextKind.Serif: fontPath = FontAssetBuilder.SerifAssetPath; break;
                case TextKind.SerifItalic: fontPath = FontAssetBuilder.SerifItalicAssetPath; break;
                case TextKind.Caption: fontPath = FontAssetBuilder.SansMediumAssetPath; break;
                case TextKind.Body: fontPath = FontAssetBuilder.SansAssetPath; break;
                default: fontPath = FontAssetBuilder.SansSemiBoldAssetPath; break;
            }
            var font = RequireAsset<TMP_FontAsset>(fontPath);
            text.font = font;
            text.fontSharedMaterial = font.material;
            text.color = color;

            if (kind == TextKind.Wordmark)
            {
                text.color = Color.white;
                text.colorGradientPreset = RequireAsset<TMP_ColorGradient>(FontAssetBuilder.GoldGradientPath);
                text.enableVertexGradient = true;
            }
            return text;
        }

        private static TMP_Text FindChildText(Component root, string name)
        {
            foreach (TMP_Text t in root.GetComponentsInChildren<TMP_Text>(true))
                if (t.name == name) return t;
            throw new InvalidOperationException($"No text '{name}' under {root.name}.");
        }

